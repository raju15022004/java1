// package Variable;

public class autoboxing {

  public static void main(String[] args){

    int x=10;
    Integer y=Integer.valueOf(x);

    System.out.println(x);
    System.out.println(y);

    Integer a=Integer.valueOf(20);
    int b=a;

    System.out.println(a);
    System.out.println(b);
  }

}
